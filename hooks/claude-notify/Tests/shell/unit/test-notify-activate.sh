(sleep 300) > "$FIFO" &
stdin_writer_pid=$!
start_epoch=$(date +%s)
TMUX="" NOTIFY_SENDER_MODE=off NOTIFY_STDIN_TIMEOUT_MS=80 NOTIFY_BIN="$FAKE_NOTIFY" NOTIFY_ARGS_LOG="$ARGS_LOG" \
  "$SCRIPT" < "$FIFO" 2>/dev/null
