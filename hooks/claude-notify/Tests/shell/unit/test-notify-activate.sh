FAKE_NOTIFY="$TMP_DIR/fake-notify.sh"
ARGS_LOG="$TMP_DIR/notify-args.log"
FIFO="$TMP_DIR/hook-input.fifo"
write_fake_notify "$FAKE_NOTIFY"
